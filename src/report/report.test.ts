describe('formatShare', () => {
  test('never prints 100% for part of a whole, or 0% for a nonzero value', () => {
    expect(formatShare(0.996)).toBe('99.6%')
    expect(formatShare(0.9996)).toBe('99.96%')
    expect(formatShare(0.99999)).toBe('99.999%')
    expect(formatShare(0.9999999)).toBe('>99.99%')
    expect(formatShare(0.0004)).toBe('0.04%')
    expect(formatShare(0.00001)).toBe('0.001%')
    expect(formatShare(0.0000001)).toBe('<0.01%')
  })

  test('whole and empty print as such', () => {
    expect(formatShare(1)).toBe('100.0%')
    expect(formatShare(0)).toBe('0.0%')
    expect(formatShare(0.5)).toBe('50.0%')
  })
})

describe('formatting helpers', () => {
  test('formatUsd keeps small amounts visible', () => {
    expect(formatUsd(0)).toBe('$0')
    expect(formatUsd(0.0042)).toBe('$0.0042')
    expect(formatUsd(1.234)).toBe('$1.23')
    expect(formatUsd(1204.4)).toBe('$1,204')
  })

  test('slugify', () => {
    expect(slugify('Debug failing CI test!')).toBe('debug-failing-ci-test')
    expect(slugify('***')).toBe('intent')
  })

  test('esc neutralizes markup from transcripts', () => {
    expect(esc('<script>alert("x")</script>')).toBe(
      '&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;',
    )
  })

  test('weekStarts spans Monday-aligned weeks', () => {
    expect(weekStarts('2026-11-04T10:00:00Z', '2026-11-17T10:00:00Z')).toEqual([
      '2026-11-02',
      '2026-11-09',
      '2026-11-16',
    ])
  })
})

const st = (tool: string, detail: string | null = null): ToolStep => ({
  tool,
  detail,
  isError: false,
  messageId: 'm',
  toolUseId: 't',
  ts: '',
})

describe('workflow similarity', () => {
  const shapeA = [
    st('Read', 'ts'),
    st('Edit', 'ts'),
    st('Bash', 'package_manager'),
    st('Bash', 'git'),
  ]
  const shapeB = [st('WebSearch'), st('WebFetch'), st('Write', 'md')]

  test('tool mix compares proportions, not order or length', () => {
    const short = [st('Read', 'ts'), st('Edit', 'ts'), st('Bash', 'git')]
    const long = [...short, ...short, ...short].reverse()
    expect(cosine(toolMix(short), toolMix(long))).toBeCloseTo(1, 10)
    expect(cosine(toolMix(shapeA), toolMix(shapeB))).toBe(0)
    expect(cosine(toolMix([]), toolMix(shapeA))).toBe(0)
  })

  test('needs 4 similar sessions; dissimilar ones are left out', () => {
    const sessions = [
      ...Array.from({ length: 4 }, (_, i) => ({ id: `a${i}`, steps: shapeA })),
      { id: 'b0', steps: shapeB },
    ]
    const wf = findWorkflow(sessions)
    expect(wf?.members.sort()).toEqual(['a0', 'a1', 'a2', 'a3'])
    expect(findWorkflow(sessions.slice(1))).toBeNull()
  })

  test('a session with a different tool mix is left out even when its tools overlap', () => {
    const outlier = [
      st('Read', 'ts'),
      ...Array.from({ length: 10 }, () => st('WebFetch')),
    ]
    const wf = findWorkflow([
      ...Array.from({ length: 4 }, (_, i) => ({ id: `a${i}`, steps: shapeA })),
      { id: 'x', steps: outlier },
    ])
    expect(wf?.members).not.toContain('x')
    expect(wf?.meanSimilarity).toBeCloseTo(1, 10)
  })
})

