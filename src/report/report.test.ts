describe('scan end to end (synthetic transcripts, fake claude)', () => {
  const ROOT = join(import.meta.dir, '..', '__fixtures__', 'projects')
  let dir: string
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'frisk-scan-'))
  })
  afterEach(() => {
    rmSync(dir, { recursive: true, force: true })
  })

  const fakeClaude: SpawnFn = async (args, stdin) => {
    if (args[1] === 'auth')
      return { exitCode: 0, stdout: '{"loggedIn":true}', stderr: '' }
    let structured: unknown
    if (stdin.includes('<cards>')) {
      const ids = [...stdin.matchAll(/^\[(s\d+)\]/gm)].map((m) => m[1])
      structured = {
        items: ids.map((id) => ({
          id,
          intent: 'Fix login test',
          category: 'fix bug',
          summary: 'x',
        })),
      }
    } else if (stdin.includes('<labels>')) {
      structured = {
        intents: [
          {
            name: 'Fix tests',
            description: 'Fixing tests.',
            labels: ['Fix login test'],
          },
        ],
      }
    } else {
      structured = {
        name: 'x',
        description: 'd',
        whenToUse: '',
        steps: ['a', 'b'],
        notes: '',
      }
    }
    return {
      exitCode: 0,
      stdout: JSON.stringify({
        is_error: false,
        structured_output: structured,
      }),
      stderr: '',
    }
  }

  const base = () => ({
    root: ROOT,
    cacheDir: join(dir, 'cache'),
    sinceMs: 0,
    sinceLabel: 'all',
    model: 'haiku',
    outDir: join(dir, 'out'),
    json: false,
    yes: true,
    sensitive: true,
    piiModel: false,
    piiModelScope: 'prompts' as const,
    salt: Buffer.alloc(32, 1),
    which: () => '/bin/claude',
    spawn: fakeClaude,
    now: () => new Date('2026-11-10T00:00:00Z'),
    log: () => undefined,
  })

  test('writes report.json and report.html with intents, waste and method', async () => {
    let printed = ''
    const res = await scan({
      ...base(),
      noLlm: false,
      out: (t) => (printed += t),
    })
    expect(res.exitCode).toBe(0)
    const report = JSON.parse(
      readFileSync(join(dir, 'out', 'report.json'), 'utf8'),
    )
    expect(report.overview.sessions).toBe(2)
    expect(report.intents).toHaveLength(1)
    expect(report.intents[0]).toMatchObject({
      name: 'Fix tests',
      sessions: 2,
      share: 1,
    })
    expect(report.waste.byKind.loop.items).toBe(1)
    expect(report.waste.byKind['interrupt-ended'].items).toBe(1)
    expect(report.source.skippedFriskSelf).toBe(1)
    expect(report.source.malformedLines).toBe(2)
    expect(report.llm.calls).toBe(2)
    const html = readFileSync(join(dir, 'out', 'report.html'), 'utf8')
    expect(html).toContain('Method and caveats')
    expect(html).toContain('API list-price equivalent')
    expect(html).not.toMatch(/<script|<link|src="http/)
    expect(printed).toContain('100.0%  Fix tests')
    expect(printed).toContain('Report:')
  })

  test('--no-llm makes no model calls', async () => {
    let calls = 0
    const spawn: SpawnFn = async () => {
      calls++
      throw new Error('should not be called')
    }
    const res = await scan({
      ...base(),
      spawn,
      noLlm: true,
      out: () => undefined,
    })
    expect(res.exitCode).toBe(0)
    expect(calls).toBe(0)
    expect(res.report?.intents).toEqual([])
    expect(existsSync(join(dir, 'out', 'report.html'))).toBe(true)
  })

  test('declining the confirmation sends nothing', async () => {
    let calls = 0
    const spawn: SpawnFn = async (args, stdin) => {
      if (args[1] !== 'auth') calls++
      return fakeClaude(args, stdin, { cwd: '' })
    }
    const res = await scan({
      ...base(),
      spawn,
      yes: false,
      noLlm: false,
      confirm: async () => false,
      out: () => undefined,
    })
    expect(res.exitCode).toBe(0)
    expect(calls).toBe(0)
    expect(existsSync(join(dir, 'out'))).toBe(false)
  })

  test('not logged in exits 2 and suggests --no-llm', async () => {
    const lines: string[] = []
    const spawn: SpawnFn = async () => ({
      exitCode: 1,
      stdout: '{"loggedIn":false}',
      stderr: '',
    })
    const res = await scan({
      ...base(),
      spawn,
      noLlm: false,
      log: (l) => lines.push(l),
      out: () => undefined,
    })
    expect(res.exitCode).toBe(2)
    expect(lines.join('\n')).toContain('--no-llm')
  })
})
