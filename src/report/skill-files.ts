import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { SkillDraft } from '../llm/prompts.ts'
import { slugify } from './format.ts'

function yamlString(s: string): string {
  return JSON.stringify(s.replace(/\s+/g, ' ').trim())
}

export function renderSkill(
  draft: SkillDraft,
  meta: { intent: string; sessions: number; date: string },
): string {
  const name = slugify(draft.name).slice(0, 40)
  const lines = [
    '---',
    `name: ${name}`,
    `description: ${yamlString(draft.description)}`,
    '---',
    '',
    `<!-- Draft generated by friskme from ${meta.sessions} sessions of "${meta.intent}" on ${meta.date}. Review and edit before installing to ~/.claude/skills/${name}/SKILL.md. -->`,
    '',
    `# ${draft.name}`,
    '',
    draft.description,
    '',
    '## When to use',
    '',
    draft.whenToUse || draft.description,
    '',
    '## Steps',
    '',
    ...draft.steps.map((s, i) => `${i + 1}. ${s}`),
  ]
  if (draft.notes) lines.push('', '## Notes', '', draft.notes)
  return `${lines.join('\n')}\n`
}

/** Writes a draft under `<out>/skills/<slug>/SKILL.md`. Never installs anything. */
export function writeSkill(
  outDir: string,
  slug: string,
  content: string,
): string {
  const rel = join('skills', slug, 'SKILL.md')
  mkdirSync(join(outDir, 'skills', slug), { recursive: true })
  writeFileSync(join(outDir, rel), content)
  return rel
}
